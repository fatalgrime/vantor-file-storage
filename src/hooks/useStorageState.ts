'use client';
import { useRef, useState } from 'react';
import { diffCollections, equal, Mutation } from '../lib/mutations';

// Serialize local saves. The server still compares each record so edits from other
// sessions produce a conflict, while unrelated records can be saved concurrently.
export function useStorageState(onState: (state: any) => void) {
  const confirmed = useRef<any>(null), optimistic = useRef<any>(null);
  const queue = useRef<Promise<void>>(Promise.resolve());
  const pending = useRef(0), generation = useRef(0);
  const onStateRef = useRef(onState); onStateRef.current = onState;
  const [saveStatus, setSaveStatus] = useState<'saved' | 'saving' | 'failed'>('saved');
  const [saveError, setSaveError] = useState('');
  function initialize(state: any) { confirmed.current = state; optimistic.current = state; }
  async function reload() {
    const response = await fetch('/api/storage-state', { cache: 'no-store' });
    const state = await response.json();
    if (!response.ok) throw new Error(state.error || 'Failed to reload storage.');
    initialize(state); onStateRef.current(state);
  }
  function persistState(patch: any): Promise<void> {
    if (!optimistic.current) return Promise.reject(new Error('Storage has not loaded.'));
    const requested: any = { ...patch };
    // Logs are generated by the server; only an explicit clear is a mutation.
    if (requested.auditLogs?.length) delete requested.auditLogs;
    const mutations = diffCollections(optimistic.current, requested);
    const metaKeys = Object.keys(requested).filter(k => ['settings', 'changelog', 'changelogs'].includes(k));
    optimistic.current = { ...optimistic.current, ...requested };
    const ownGeneration = generation.current;
    pending.current++; setSaveStatus('saving'); setSaveError('');
    const task = queue.current.then(async () => {
      if (ownGeneration !== generation.current) throw new Error('Save cancelled after an earlier failure. Please try again.');
      const rebased: Mutation[] = mutations.map(m => {
        const current = confirmed.current[m.collection]?.find((r: any) => r.id === m.id) || null;
        if (Boolean(current) !== Boolean(m.before)) throw new Error('This item changed. Reload and try again.');
        if (!m.after && m.before && current) {
          const comparable = (record: any) => Object.fromEntries(Object.entries(record).filter(([key]) => !['updatedAt', 'downloadCount', 'viewsCount', 'downloadsCount', 'accessCount', 'selfDestructed'].includes(key)));
          if (!equal(comparable(current), comparable(m.before))) throw new Error('This item changed before it could be deleted. Reload and try again.');
        }
        let after = m.after;
        if (after && m.before && current) {
          after = { ...current };
          for (const key of new Set([...Object.keys(m.before), ...Object.keys(m.after!)])) {
            if (!equal(m.before[key], m.after![key])) {
              if (!['updatedAt', 'downloadCount'].includes(key) && !equal(current[key], m.before[key])) throw new Error('This item changed in another session. Reload and try again.');
              if (key in m.after!) after![key] = m.after![key]; else delete after![key];
            }
          }
        }
        return { ...m, before: current, after };
      });
      const metadata = Object.fromEntries(metaKeys.map(k => [k, { before: confirmed.current[k], after: requested[k] }]));
      const response = await fetch('/api/storage-state', { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ mutations: rebased, metadata }) });
      const state = await response.json();
      if (!response.ok) throw new Error(state.error || 'Failed to save changes.');
      confirmed.current = state;
    }).catch(async (error) => {
      if (ownGeneration === generation.current) {
        generation.current++;
        try { await reload(); } catch { optimistic.current = confirmed.current; onStateRef.current(confirmed.current); }
        setSaveStatus('failed'); setSaveError(error.message);
      }
      throw error;
    }).finally(() => {
      pending.current--;
      if (!pending.current && ownGeneration === generation.current) {
        optimistic.current = confirmed.current;
        onStateRef.current(confirmed.current); setSaveStatus('saved');
      }
    });
    queue.current = task.catch(() => {});
    return task;
  }
  return { persistState, initialize, reload, saveStatus, saveError };
}
